def unlocked_chapters(unlocked: set) -> list:
    """已解锁的章节（按剧情顺序）。"""
    return [c for c in CHAPTERS if c.is_unlocked(unlocked)]


def newly_unlocked_chapters(before: set, after: set) -> list:
    """本次新解锁的章节（剧情播报用）。"""
    return [c for c in CHAPTERS if c.is_unlocked(after) and not c.is_unlocked(before)]



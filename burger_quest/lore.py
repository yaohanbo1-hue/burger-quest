def state_copy(key: str, **kwargs) -> str:
    """取一条状态文案并填充占位符；未知 key 返回 key 本身（测试锁定无静默失败）。"""
    template = STATE_COPY.get(key)
    if template is None:
        return key
    return template.format(**kwargs) if kwargs else template



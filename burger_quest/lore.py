@dataclass(frozen=True)
class Chapter:
    id: str            # 唯一标识
    index: int         # 章节序号（1 起）
    name: str          # 章名
    requires: tuple    # 解锁所需成就 id（全部解锁才解锁本章）
    unlock_text: str   # 解锁时播报的叙事（虚构，不含真实数据）
    summary: str       # 一句话大纲（清单/文档用）

    def is_unlocked(self, unlocked: set) -> bool:
        return all(a in unlocked for a in self.requires)


